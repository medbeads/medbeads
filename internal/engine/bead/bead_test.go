// TestNormalize_DedupAndSort exercises Normalize (and, through it,
// normalizeStrings) directly, across Parents/Amends/Retracts.
func TestNormalize_DedupAndSort(t *testing.T) {
	b := Bead{
		Type:      "encounter",
		Timestamp: "2026-01-01T00:00:00Z",
		Parents:   []string{"z9", "a1", "z9", "m5", "a1"},
		Amends:    []string{"m9", "m1", "m9"},
		Retracts:  []string{"r9", "r1", "r9"},
		Content:   map[string]any{},
	}

	n := Normalize(b)

	wantParents := []string{"a1", "m5", "z9"}
	if !equalStrings(n.Parents, wantParents) {
		t.Errorf("Normalize(b).Parents = %v, want %v", n.Parents, wantParents)
	}

	wantAmends := []string{"m1", "m9"}
	if !equalStrings(n.Amends, wantAmends) {
		t.Errorf("Normalize(b).Amends = %v, want %v", n.Amends, wantAmends)
	}

	wantRetracts := []string{"r1", "r9"}
	if !equalStrings(n.Retracts, wantRetracts) {
		t.Errorf("Normalize(b).Retracts = %v, want %v", n.Retracts, wantRetracts)
	}
}

// TestNormalize_NilBecomesEmptySlice confirms nil Parents/Amends/Retracts
// normalize to a non-nil empty slice (so they marshal as JSON `[]`, keeping
// the hash payload shape stable and matching TestGoldenID_Minimal's
// canonical form).
func TestNormalize_NilBecomesEmptySlice(t *testing.T) {
	b := Bead{Type: "t", Timestamp: "2026-01-01T00:00:00Z", Content: map[string]any{}}
	n := Normalize(b)
	if n.Parents == nil {
		t.Error("Normalize(b).Parents is nil, want non-nil empty slice")
	}
	if len(n.Parents) != 0 {
		t.Errorf("Normalize(b).Parents = %v, want empty", n.Parents)
	}
	if n.Amends == nil {
		t.Error("Normalize(b).Amends is nil, want non-nil empty slice")
	}
	if len(n.Amends) != 0 {
		t.Errorf("Normalize(b).Amends = %v, want empty", n.Amends)
	}
	if n.Retracts == nil {
		t.Error("Normalize(b).Retracts is nil, want non-nil empty slice")
	}
	if len(n.Retracts) != 0 {
		t.Errorf("Normalize(b).Retracts = %v, want empty", n.Retracts)
	}
}

// TestFormatIDAndParseID exercises the "sha256:" display-prefix helpers.
// Per specs/DESIGN_v3.md §4, the prefix is a presentation-layer concern only
// — internal IDs (as returned by ComputeID) are always plain hex.
func TestFormatIDAndParseID(t *testing.T) {
	b, err := WithID(fixedBead())
	if err != nil {
		t.Fatalf("WithID: %v", err)
	}

	if strings.HasPrefix(b.ID, IDPrefix) {
		t.Errorf("ComputeID output has unexpected %q prefix: %s", IDPrefix, b.ID)
	}

	formatted := FormatID(b.ID)
	if formatted != IDPrefix+b.ID {
		t.Errorf("FormatID(%s) = %s, want %s%s", b.ID, formatted, IDPrefix, b.ID)
	}

	parsedFromPrefixed, err := ParseID(formatted)
	if err != nil {
		t.Fatalf("ParseID(%s): %v", formatted, err)
	}
	if parsedFromPrefixed != b.ID {
		t.Errorf("ParseID(%s) = %s, want %s", formatted, parsedFromPrefixed, b.ID)
	}

	parsedBare, err := ParseID(b.ID)
	if err != nil {
		t.Fatalf("ParseID(%s): %v", b.ID, err)
	}
	if parsedBare != b.ID {
		t.Errorf("ParseID(%s) = %s, want %s", b.ID, parsedBare, b.ID)
	}
}

// TestParseID_Rejects covers malformed IDs: wrong length, non-hex, and
// upper/mixed-case hex (canonical storage is lower-case; ParseID must not
// silently normalize case, since that would let two different-looking
// strings address the same Bead undetected upstream of this helper).
func TestParseID_Rejects(t *testing.T) {
	b, err := WithID(fixedBead())
	if err != nil {
		t.Fatalf("WithID: %v", err)
	}

	cases := []struct {
		name string
		id   string
	}{
		{"empty", ""},
		{"too short", b.ID[:10]},
		{"too long", b.ID + "00"},
		{"non-hex characters", "zz" + b.ID[2:]},
		{"upper-case hex", strings.ToUpper(b.ID)},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			if _, err := ParseID(tc.id); err == nil {
				t.Errorf("ParseID(%q) = nil error, want error", tc.id)
			}
		})
	}
}

// equalStrings is a small test helper (avoids importing slices/reflect for
// a single comparison).
func equalStrings(a, b []string) bool {
	if len(a) != len(b) {
		return false
	}
	for i := range a {
		if a[i] != b[i] {
			return false
		}
	}
	return true
}
