// This file ports the structure of v2's Bead hashing/CAS tests
// (git show v2.2.0:core/store/cas_test.go on the v2-maintenance branch,
// specifically TestSaveAndLoadFromCAS / TestSaveToCAS_HashIsDeterministic)
// to v3's bead package: fixed-input round trip, hash determinism, and (new
// in v3) explicit tamper detection via Verify.
//
// v3's hash-target field set differs from v2 (see specs/DESIGN_v3.md §4):
// v2 hashed {type, timestamp, parents, content} via a plain
// json.MarshalIndent (no canonicalization scheme, no author/antigens/
// evidence, no dedup/sort of parents). v3.0 hashed
// {type, timestamp, author, parents, antigens, content, evidence} via RFC
// 8785 (JCS), with parents/antigens normalized (dedup + sort) first.
//
// v3.1 (specs/DESIGN_v3.1_draft.md §2, "事実と解釈の二層分離") changed the
// hash-target field set again: antigens is removed entirely (tag derivation
// moved to the index projection, see antigen.Extract) and amends/retracts
// are added (dedup+sort normalized exactly like parents). The payload shape
// is now {type, timestamp, author, parents, amends, retracts, content,
// evidence}. Because the payload shape itself changed a second time, every
// golden ID below was regenerated by running this package's own
// implementation once against the v3.1 field set (see
// TestGoldenID_FixedBead / TestGoldenID_Minimal) and is pinned as a new
// regression baseline: v3.0's golden values do not carry over (removing
// antigens and adding amends/retracts changes the JCS payload's key set, so
// every existing v3.0 Bead ID is intentionally NOT reproducible under this
// version — the one-time, all-at-once re-ingest called for by
// specs/DESIGN_v3.1_draft.md §0 point 7 is what absorbs this). If a future
// change to Canonicalize/ComputeID (or an upstream gowebpki/jcs version
// bump) alters these values again, that is a signal requiring explicit
// review — Bead IDs must never change silently, since they are the join key
// for a Merkle DAG.

// fixedBead is the canonical fixture used by the golden hash tests below.
func fixedBead() Bead {
	return Bead{
		Type:      "observation",
		Timestamp: "2026-03-01T10:00:00Z",
		Author:    "did:medbeads:doctor:12345",
		Parents:   []string{"b2", "a1"},
		Amends:    []string{"m2", "m1"},
		Retracts:  []string{"r2", "r1"},
		Content: map[string]any{
			"bp":   "120/80",
			"note": "stable",
		},
		Evidence: []Evidence{
			{URI: "s3://bucket/ct.dcm", MimeType: "application/dicom", Hash: "sha256:abc123"},
		},
	}
}

// TestGoldenID_FixedBead pins ComputeID's output for a fixed, representative
// Bead (all hash-target fields populated, including amends/retracts). This
// value was generated by running ComputeID once against the v3.1
// implementation in this package (see this file's header comment on why
// v3.0's golden values do not carry over) and is now a regression baseline:
// any future diff must explain why this constant changed.
func TestGoldenID_FixedBead(t *testing.T) {
	const wantID = "50d8b41778d2080b22a6c0b9951c6aef74f5182a605d9423ab5f43878ebec829"
	const wantCanonical = `{"amends":["m1","m2"],"author":"did:medbeads:doctor:12345",` +
		`"content":{"bp":"120/80","note":"stable"},` +
		`"evidence":[{"hash":"sha256:abc123","mime_type":"application/dicom","uri":"s3://bucket/ct.dcm"}],` +
		`"parents":["a1","b2"],"retracts":["r1","r2"],"timestamp":"2026-03-01T10:00:00Z","type":"observation"}`

	b := fixedBead()

	canon, err := Canonicalize(b)
	if err != nil {
		t.Fatalf("Canonicalize: %v", err)
	}
	if string(canon) != wantCanonical {
		t.Errorf("Canonicalize mismatch:\n got  = %s\n want = %s", canon, wantCanonical)
	}

	id, err := ComputeID(b)
	if err != nil {
		t.Fatalf("ComputeID: %v", err)
	}
	if id != wantID {
		t.Errorf("ComputeID = %s, want %s", id, wantID)
	}
	if len(id) != HexIDLen {
		t.Errorf("ComputeID length = %d, want %d", len(id), HexIDLen)
	}
}

// TestGoldenID_Minimal pins ComputeID for a Bead with only the required
// fields set (no author, no evidence, empty parents/amends/retracts) — the
